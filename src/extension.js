const vscode = require('vscode');
const fs = require('fs');
const path = require('path');
const os = require('os');

function activate(context) {
    console.log('恭喜，你的插件 "sdcc-vscode-bugfixer" 现已激活！');

    // 注册命令
    let disposable = vscode.commands.registerCommand('sdcc-vscode-bugfixer.fixIntellisense', function () {
        const workspaceFolder = vscode.workspace.workspaceFolders ? vscode.workspace.workspaceFolders[0].uri.fsPath : null;
        if (!workspaceFolder) {
            vscode.window.showErrorMessage('请先打开一个项目文件夹！');
            return;
        }

        const vscodeDir = path.join(workspaceFolder, '.vscode');
        const shimFile = path.join(vscodeDir, 'sdcc_shim.h');
        const settingsFile = path.join(vscodeDir, 'settings.json');
        const platformioIniFile = path.join(workspaceFolder, 'platformio.ini');
        const gitignoreFile = path.join(workspaceFolder, '.gitignore');

        // ==========================================
        // 1. 生成垫片文件 (sdcc_shim.h)
        // ==========================================
        const shimContent = `#ifndef __SDCC_SHIM_H__
#define __SDCC_SHIM_H__
#ifndef __SDCC
    #define __sbit   unsigned char
    #define __bit    unsigned char
    #define __sfr    unsigned char
    #define __sfr16  unsigned int
    #define __sfr32  unsigned long
    #define __idata
    #define __xdata
    #define __code
    #define __data
    #define __near
    #define __far
    #define __at(x)
    #define __interrupt(x)
    #define __using(x)
    #define __banked
    #define __reentrant
    #define __naked
    #define __critical
#endif
#endif
`;
        if (!fs.existsSync(vscodeDir)) {
            fs.mkdirSync(vscodeDir, { recursive: true });
        }
        fs.writeFileSync(shimFile, shimContent, 'utf8');

        // ==========================================
        // 2. 写入/更新 .vscode/settings.json (桥 1：forcedInclude)
        // ==========================================
        let settings = {};
        if (fs.existsSync(settingsFile)) {
            try {
                settings = JSON.parse(fs.readFileSync(settingsFile, 'utf8'));
            } catch (e) {
                console.error('settings.json 解析失败，将重置');
            }
        }
        // 注入 forcedInclude
        settings["C_Cpp.default.forcedInclude"] = ["${workspaceFolder}/.vscode/sdcc_shim.h"];
        fs.writeFileSync(settingsFile, JSON.stringify(settings, null, 4), 'utf8');

        // ==========================================
        // 3. 修改 platformio.ini (桥 2：includePath)
        // ==========================================
        if (fs.existsSync(platformioIniFile)) {
            let iniContent = fs.readFileSync(platformioIniFile, 'utf8');
            const sdccIncludeDir = path.join(os.homedir(), '.platformio', 'packages', 'toolchain-sdcc', 'include').replace(/\\/g, '/');
            const buildFlag = `-I${sdccIncludeDir}`;
            
            // 检查是否已经包含该路径
            if (!iniContent.includes('toolchain-sdcc')) {
                // 简单策略：直接在文件末尾追加（PIO 会识别为全局或当前 env 配置）
                // 为了更规范，我们可以追加到文件末尾
                iniContent += `\n; --- SDCC IntelliSense Fix (Auto-Generated by sdcc-vscode-bugfixer) ---\nbuild_flags = ${buildFlag}\n`;
                fs.writeFileSync(platformioIniFile, iniContent, 'utf8');
                console.log('已自动向 platformio.ini 注入 includePath');
            }
        }

        // ==========================================
        // 4. 修改 .gitignore (保护配置文件)
        // ==========================================
        let gitignoreContent = fs.existsSync(gitignoreFile) ? fs.readFileSync(gitignoreFile, 'utf8') : '';
        const ignoresToAdd = ['.vscode/settings.json', '.vscode/c_cpp_properties.json'];
        let needsUpdate = false;
        
        ignoresToAdd.forEach(ig => {
            if (!gitignoreContent.includes(ig)) {
                gitignoreContent += `\n${ig}`;
                needsUpdate = true;
            }
        });
        
        if (needsUpdate) {
            fs.writeFileSync(gitignoreFile, gitignoreContent, 'utf8');
            console.log('已自动更新 .gitignore');
        }

        // ==========================================
        // 5. 成功提示
        // ==========================================
        vscode.window.showInformationMessage('🎉 修复成功！(已配置 settings.json + platformio.ini + .gitignore)', '去重置 IntelliSense')
            .then(selection => {
                if (selection === '去重置 IntelliSense') {
                    vscode.commands.executeCommand('C_Cpp.ResetDatabase');
                }
            });
    });

    context.subscriptions.push(disposable);
}

function deactivate() {}

module.exports = {
    activate,
    deactivate
}